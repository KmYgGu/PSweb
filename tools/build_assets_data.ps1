# tools\에셋갱신.bat 에서 실행: assets 폴더의 PNG -> js\assets_data.js (동영상 저장용 그림 사본)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$jsDir = Join-Path $root 'js'
$js = (Get-ChildItem $jsDir -Filter *.js | Where-Object { $_.Name -ne 'assets_data.js' } | Sort-Object Name | ForEach-Object { [IO.File]::ReadAllText($_.FullName, [Text.Encoding]::UTF8) }) -join ''
$assets = Join-Path $root 'assets'
$list = @()
foreach ($f in (Get-ChildItem $assets -Recurse -File -Filter *.png)) {
  $rel = 'assets/' + $f.FullName.Substring($assets.Length + 1).Replace('\', '/')
  $folder = $rel.Substring(0, $rel.LastIndexOf('/') + 1)
  if ($js.Contains($rel) -or $js.Contains($folder + "'") -or $js.Contains($folder + '"')) { $list += ,@($rel, $f.FullName) }
}
$list = $list | Sort-Object { $_[0] } -CaseSensitive
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("/* AUTO-GENERATED by tools\build_assets_data.ps1 (run tools\bat). Video export only. */`n")
[void]$sb.Append('window.ASSET_DATA_META = { built: "' + (Get-Date -Format 'yyyy-MM-dd HH:mm') + '", count: ' + $list.Count + " };`nwindow.ASSET_DATA = {`n")
foreach ($e in $list) { [void]$sb.Append('"' + $e[0] + '":"data:image/png;base64,' + [Convert]::ToBase64String([IO.File]::ReadAllBytes($e[1])) + "`",`n") }
[void]$sb.Append("};`n")
[IO.File]::WriteAllText((Join-Path $jsDir 'assets_data.js'), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("OK: " + $list.Count + " PNG -> js\assets_data.js")
