# 박스/개발용: tools/에셋갱신.bat (PowerShell) 과 같은 규칙으로 js/assets_data.js 생성
import os, re, base64, datetime
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = ''.join(open(os.path.join(root, 'js', f), encoding='utf-8').read() for f in sorted(os.listdir(os.path.join(root, 'js'))) if f.endswith('.js') and f != 'assets_data.js')
out = []
for r, d, fs in os.walk(os.path.join(root, 'assets')):
    d.sort()
    for f in sorted(fs):
        if not f.lower().endswith('.png'): continue
        rel = os.path.relpath(os.path.join(r, f), root).replace('\\', '/')
        folder = rel.rsplit('/', 1)[0] + '/'
        if rel in js or (folder + "'") in js or (folder + '"') in js:
            out.append(rel)
out.sort()
with open(os.path.join(root, 'js', 'assets_data.js'), 'w', encoding='utf-8', newline='\n') as w:
    w.write('/* AUTO-GENERATED by tools\\build_assets_data.ps1 (run tools\\bat). Video export only. */\n')
    w.write('window.ASSET_DATA_META = { built: "%s", count: %d };\nwindow.ASSET_DATA = {\n' % (datetime.datetime.now().strftime('%Y-%m-%d %H:%M'), len(out)))
    for rel in out:
        b = base64.b64encode(open(os.path.join(root, rel), 'rb').read()).decode()
        w.write('"%s":"data:image/png;base64,%s",\n' % (rel, b))
    w.write('};\n')
print(len(out), 'files')
